import React, { useEffect, useState } from 'react';
import {
  X,
  Sparkles,
  ShieldAlert,
  ShieldCheck,
  AlertTriangle,
  Scale,
  RefreshCw,
  FileText,
  Info,
  CheckCircle,
} from 'lucide-react';
import { MaskResult, PrivacyRiskAnalysis } from '../../types/index.ts';
import { api } from '../../services/api.ts';

interface RiskAssessmentModalProps {
  isOpen: boolean;
  onClose: () => void;
  maskResult: MaskResult | null;
  originalText: string;
}

export const RiskAssessmentModal: React.FC<RiskAssessmentModalProps> = ({
  isOpen,
  onClose,
  maskResult,
  originalText,
}) => {
  const [loading, setLoading] = useState(false);
  const [analysis, setAnalysis] = useState<PrivacyRiskAnalysis | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (isOpen && maskResult) {
      loadAssessment();
    }
  }, [isOpen, maskResult]);

  const loadAssessment = async () => {
    if (!maskResult) return;
    setLoading(true);
    setError(null);

    const categoryCounts: Record<string, number> = {};
    for (const ent of maskResult.entities) {
      categoryCounts[ent.category] = (categoryCounts[ent.category] || 0) + 1;
    }

    try {
      const res = await api.evaluateRisk({
        categoryCounts,
        totalEntities: maskResult.entitiesCount,
        textLength: maskResult.statistics.characterCount,
        inputType: maskResult.fileName ? 'file' : 'text',
        currentStrategy: maskResult.transformations[0]?.strategyApplied || 'CATEGORY_TAG',
        sampleSanitizedContext: maskResult.maskedText.substring(0, 300),
      });

      setAnalysis(res.data);
    } catch (err: any) {
      setError(err.message || 'Failed to complete risk evaluation.');
    } finally {
      setLoading(false);
    }
  };

  if (!isOpen || !maskResult) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/60 backdrop-blur-xs">
      <div className="bg-white rounded-2xl max-w-3xl w-full max-h-[90vh] overflow-hidden flex flex-col shadow-2xl border border-slate-200">
        {/* Header */}
        <div className="px-6 py-4 bg-gradient-to-r from-blue-900 to-indigo-900 text-white flex items-center justify-between shrink-0">
          <div className="flex items-center gap-2.5">
            <div className="p-2 bg-blue-700/50 rounded-lg border border-blue-500/30">
              <Sparkles className="w-5 h-5 text-blue-300" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-base font-bold">Gemini Privacy Risk &amp; Regulatory Audit</h2>
                <span className="text-[10px] font-mono uppercase px-2 py-0.5 rounded bg-blue-800 text-blue-200 border border-blue-600">
                  AI-Generated Recommendation
                </span>
              </div>
              <p className="text-xs text-blue-200">
                Threat modeling &amp; compliance strategy synthesized by Gemini 3.8 Flash
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-blue-200 hover:text-white rounded-lg hover:bg-blue-800/60 transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Body */}
        <div className="p-6 overflow-y-auto space-y-5 flex-1 text-slate-800">
          {/* Important Distinction Banner */}
          <div className="p-3 bg-blue-50 border border-blue-200 rounded-lg text-xs text-blue-900 flex items-start gap-2.5">
            <Info className="w-4 h-4 text-blue-700 shrink-0 mt-0.5" />
            <div className="leading-relaxed">
              <strong>Architecture Boundary:</strong> The sensitive entities were detected deterministically by backend rule algorithms. The risk score, regulatory breakdown, and remediation rationale below are generated by Gemini to assist your security team.
            </div>
          </div>

          {loading ? (
            <div className="py-16 text-center space-y-3">
              <RefreshCw className="w-8 h-8 text-blue-600 animate-spin mx-auto" />
              <div className="text-sm font-semibold text-slate-800">
                Synthesizing Threat Vectors &amp; Regulatory Exposures...
              </div>
              <p className="text-xs text-slate-500">
                Consulting GDPR, HIPAA, and PCI-DSS compliance frameworks via Gemini
              </p>
            </div>
          ) : error ? (
            <div className="p-4 bg-rose-50 border border-rose-200 text-rose-800 rounded-lg text-xs space-y-2">
              <div className="font-bold flex items-center gap-1.5">
                <AlertTriangle className="w-4 h-4 text-rose-600" />
                <span>Evaluation Error</span>
              </div>
              <p>{error}</p>
              <button
                onClick={loadAssessment}
                className="mt-2 px-3 py-1 bg-rose-700 text-white rounded text-xs font-semibold cursor-pointer"
              >
                Retry Assessment
              </button>
            </div>
          ) : analysis ? (
            <div className="space-y-5">
              {/* Score & Executive Summary */}
              <div className="grid grid-cols-1 md:grid-cols-3 gap-4 p-4 bg-slate-50 border border-slate-200 rounded-xl">
                <div className="text-center md:border-r border-slate-200 pr-2 flex flex-col justify-center items-center">
                  <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
                    Privacy Risk Score
                  </span>
                  <div
                    className={`text-4xl font-extrabold font-mono mt-1 ${
                      analysis.riskScore >= 70
                        ? 'text-rose-600'
                        : analysis.riskScore >= 40
                        ? 'text-amber-600'
                        : 'text-emerald-600'
                    }`}
                  >
                    {analysis.riskScore}/100
                  </div>
                  <span
                    className={`text-xs font-bold uppercase mt-1 px-2 py-0.5 rounded-full ${
                      analysis.overallRiskLevel === 'critical' || analysis.overallRiskLevel === 'high'
                        ? 'bg-rose-100 text-rose-800'
                        : 'bg-emerald-100 text-emerald-800'
                    }`}
                  >
                    {analysis.overallRiskLevel} Risk Level
                  </span>
                </div>

                <div className="md:col-span-2 flex flex-col justify-center">
                  <span className="text-xs font-bold text-slate-700 mb-1 flex items-center gap-1.5">
                    <ShieldAlert className="w-4 h-4 text-blue-700" />
                    <span>Executive Threat Brief</span>
                  </span>
                  <p className="text-xs text-slate-600 leading-relaxed">
                    {analysis.executiveSummary}
                  </p>
                </div>
              </div>

              {/* Identified Risk Vectors */}
              <div className="space-y-2.5">
                <h3 className="text-xs font-bold text-slate-900 uppercase tracking-wider">
                  Identified Exposure Vectors
                </h3>
                <div className="grid grid-cols-1 gap-2.5">
                  {analysis.identifiedRiskVectors?.map((vec, idx) => (
                    <div
                      key={idx}
                      className="p-3 bg-white border border-slate-200 rounded-lg text-xs space-y-1"
                    >
                      <div className="flex items-center justify-between">
                        <span className="font-bold text-slate-800">{vec.title}</span>
                        <span
                          className={`text-[10px] font-bold uppercase px-2 py-0.5 rounded ${
                            vec.severity === 'critical'
                              ? 'bg-rose-100 text-rose-800'
                              : vec.severity === 'high'
                              ? 'bg-amber-100 text-amber-900'
                              : 'bg-blue-100 text-blue-800'
                          }`}
                        >
                          {vec.severity}
                        </span>
                      </div>
                      <p className="text-slate-600 leading-normal">{vec.description}</p>
                    </div>
                  ))}
                </div>
              </div>

              {/* Regulatory Impact Matrix */}
              <div className="space-y-2.5">
                <h3 className="text-xs font-bold text-slate-900 uppercase tracking-wider flex items-center gap-1.5">
                  <Scale className="w-3.5 h-3.5 text-blue-700" />
                  <span>Regulatory Impact Analysis</span>
                </h3>
                <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
                  {analysis.regulatoryImpacts?.map((reg, idx) => (
                    <div
                      key={idx}
                      className="p-3.5 rounded-lg border border-slate-200 bg-slate-50 space-y-1.5 text-xs"
                    >
                      <div className="font-bold text-blue-900">{reg.regulation}</div>
                      <div className="text-slate-600 text-[11px] leading-normal">
                        <strong>Scope:</strong> {reg.applicability}
                      </div>
                      <div className="text-slate-700 text-[11px] leading-normal font-medium bg-white p-2 rounded border border-slate-200">
                        <strong>Mandated Safeguard:</strong> {reg.safeguardRequirements}
                      </div>
                    </div>
                  ))}
                </div>
              </div>

              {/* Strategy Recommendations */}
              <div className="space-y-2.5">
                <h3 className="text-xs font-bold text-slate-900 uppercase tracking-wider">
                  Recommended Masking Policy by Classification
                </h3>
                <div className="divide-y divide-slate-100 border border-slate-200 rounded-lg overflow-hidden text-xs">
                  {analysis.recommendedStrategies?.map((rec, idx) => (
                    <div key={idx} className="p-3 bg-white flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                      <div>
                        <div className="font-bold text-slate-800">{rec.category}</div>
                        <div className="text-slate-500 text-[11px]">{rec.rationale}</div>
                      </div>
                      <span className="font-mono text-[11px] font-bold text-blue-800 bg-blue-50 px-2.5 py-1 rounded border border-blue-200 shrink-0">
                        {rec.recommendedStrategy}
                      </span>
                    </div>
                  ))}
                </div>
              </div>

              {/* Mandatory Legal & Accuracy Disclaimer */}
              <div className="p-3 rounded-lg bg-slate-100 border border-slate-300 text-[11px] text-slate-500 leading-relaxed">
                <strong>Compliance Disclaimer:</strong> {analysis.disclaimer}
              </div>
            </div>
          ) : null}
        </div>

        {/* Footer */}
        <div className="px-6 py-3.5 bg-slate-50 border-t border-slate-200 flex items-center justify-between shrink-0">
          <div className="text-[11px] text-slate-400">
            Powered by Google GenAI TypeScript SDK (gemini-3.8-flash)
          </div>
          <button
            onClick={onClose}
            className="px-4 py-2 bg-slate-800 hover:bg-slate-900 text-white text-xs font-semibold rounded-lg cursor-pointer transition-colors"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
};
